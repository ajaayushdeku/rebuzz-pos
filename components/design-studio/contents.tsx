export type LayerType = "text" | "image" | "shape" | "banner";

export type ShapeType =
  | "rectangle"
  | "rounded-rectangle"
  | "circle"
  | "line"
  | "triangle"
  | "diamond"
  | "pentagon"
  | "hexagon"
  | "star"
  | "arrow";

export type DesignLayer = {
  id: string;
  name: string;
  type: LayerType;
  icon: LucideIcon;
  visible: boolean;
  fontSize: number;
  opacity: number;
  content: string;
  color: string;
  backgroundColor?: string;
  x: number;
  y: number;
  width: number;
  height: number;
  src?: string;
  shapeType?: ShapeType;
  fillEnabled?: boolean;
  strokeWidth?: number;

  rotation?: number;
  fontFamily?: string;
  fontWeight?: number;
  fontStyle?: "normal" | "italic";
  textAlign?: "left" | "center" | "right";
  textDecoration?: "none" | "underline" | "line-through";
  lineHeight?: number;
  letterSpacing?: number;

  // Banner-specific properties
  subtitle?: string;
  buttonText?: string;
  borderRadius?: number;
  padding?: number;
  borderColor?: string;
  borderWidth?: number;

  // Banner button properties
  buttonAlignment?: "left" | "center" | "right";
  buttonWidth?: number;
  buttonHeight?: number;
  buttonFontSize?: number;
  buttonPaddingX?: number;
  buttonPaddingY?: number;
  buttonBackgroundColor?: string;
  buttonColor?: string;
  buttonBorderRadius?: number;

  // Image transform
  objectFit?: "cover" | "contain" | "fill" | "none";
  lockAspectRatio?: boolean;
  flipHorizontal?: boolean;
  flipVertical?: boolean;

  borderEnabled?: boolean;

  // Image shadow
  shadowEnabled?: boolean;
  shadowColor?: string;
  shadowBlur?: number;
  shadowOffsetX?: number;
  shadowOffsetY?: number;

  // Image adjustments
  brightness?: number;
  contrast?: number;
  saturation?: number;
  grayscale?: number;
  sepia?: number;
  blur?: number;
  hueRotate?: number;
  invert?: number;
};

